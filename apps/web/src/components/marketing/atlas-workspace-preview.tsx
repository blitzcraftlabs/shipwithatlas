/** Renders `inline code` spans inside a markdown line. */
function MarkdownInline({ text }: { text: string }) {
  return (
    <>
      {text.split(/(`[^`]+`)/).map((part, index) =>
        part.startsWith("`") ? (
          <code key={index} className="bp-demo__md-code">
            {part}
          </code>
        ) : (
          <React.Fragment key={index}>{part}</React.Fragment>
        )
      )}
    </>
  )
}

interface AtlasWorkspacePreviewProps {
  className?: string
}

/**
 * Editor-style view of a freshly generated Atlas workspace: the file tree on
 * the left, the generated AGENTS.md open on the right. The window is
 * decorative for assistive tech; the figcaption carries its meaning.
 */
